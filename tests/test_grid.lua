-- No Yazi process or file actions: verify the same model used by the UI.
local plugin=dofile('navigation/yazi/plugins/edex-grid.yazi/main.lua')
local m=plugin.model
local g=m.layout(91,14,0,40)
assert(g.cols==7 and g.rows==2 and g.size==14 and g.shortcuts==2 and g.start==0)
assert(m.hit(g,1,1,91,14)==0)
assert(m.hit(g,14,1,91,14)==1)
assert(m.hit(g,27,1,91,14)==2)
assert(m.hit(g,90,13,91,14)==nil) -- unused row gutter is not a file
assert(m.hit(g,-1,1,91,14)==nil)
assert(m.hit(g,91,1,91,14)==nil)
assert(m.target(0,40,7,2,'down')==7)
assert(m.target(7,40,7,2,'up')==0)
assert(m.target(0,40,7,2,'left')==0)
assert(m.target(39,40,7,2,'right')==39)
assert(m.target(0,40,7,2,'pagedown')==14)
assert(m.target(14,40,7,2,'pageup')==0)
assert(m.target(10,40,7,2,'last')==39)
assert(m.target(39,40,7,2,'first')==0)
assert(m.target(0,0,7,2,'right')==nil)
local second=m.layout(91,14,14,40)
assert(second.start==14)
assert(m.hit(second,1,1,91,14)==14)
assert(m.hit(m.layout(91,14,0,0),27,1,91,14)==nil)
local narrow=m.layout(5,1,0,4)
assert(narrow.cols==1 and narrow.shortcuts==0 and narrow.pitch==1)
assert(m.hit(narrow,1,0,5,1)==0)
print('Grid geometry, paging, boundaries, empty and narrow views passed')
